import { Command as CommandPrimitive } from "cmdk"
import { SearchIcon } from "lucide-react"
import type { ComponentProps, HTMLAttributes } from "react"

import {
  Dialog,
  DialogContent,
  DialogTitle,
  type DialogProps,
} from "@/components/ui/dialog"
import { cn } from "@/utils/cn"

function Command({
  className,
  ...props
}: ComponentProps<typeof CommandPrimitive>) {
  return (
    <CommandPrimitive
      data-slot="command"
      className={cn(
        "flex h-full w-full flex-col overflow-hidden rounded-md bg-popover text-popover-foreground",
        className
      )}
      {...props}
    />
  )
}

function CommandDialog({
  title,
  description,
  children,
  dialogProps,
  commandProps,
}: {
  title?: string
  description?: string
  children: React.ReactNode
  dialogProps?: DialogProps
  commandProps?: ComponentProps<typeof CommandPrimitive>
}) {
  return (
    <Dialog {...dialogProps}>
      <DialogContent className="overflow-hidden p-0 sm:max-w-lg [&>button:last-child]:hidden">
        <DialogTitle className="sr-only">{title ?? "命令面板"}</DialogTitle>
        {description && <p className="sr-only">{description}</p>}
        <Command
          {...commandProps}
          className={cn(
            "border-none bg-transparent shadow-none",
            commandProps?.className
          )}
        >
          {children}
        </Command>
      </DialogContent>
    </Dialog>
  )
}

function CommandInput({
  className,
  wrapperClassName,
  ...props
}: ComponentProps<typeof CommandPrimitive.Input> & {
  wrapperClassName?: string
}) {
  return (
    <div
      data-slot="command-input-wrapper"
      className={cn("flex items-center gap-2 border-b px-3", wrapperClassName)}
    >
      <SearchIcon className="size-4 shrink-0 opacity-50" />
      <CommandPrimitive.Input
        data-slot="command-input"
        className={cn(
          "flex h-10 w-full rounded-md bg-transparent py-3 text-sm outline-none placeholder:text-muted-foreground disabled:cursor-not-allowed disabled:opacity-50",
          className
        )}
        {...props}
      />
    </div>
  )
}

